import { type DisplayType, textCoding } from '../type.js';
import { bar, disc, light } from './bars.js';

// The Siemens DL-3422's 20 segments and two dots, placed from its layout drawing (a 166 × 276
// drawing at 20 units to the cell's one). Named as `twentytwo` names them where they match; `n` is
// the lower left's second diagonal, the `\` crossing `k`; `o` hangs below the center, floored by
// `q1 q2`; `udot` sits over the left of the center, `ldot` under it, for i, j, `.`, `,` and `:`.

const W = 0.8;
const at = (v: number) => (v - 3) / 20 + 1;
const seg = (x1: number, y1: number, x2: number, y2: number) =>
  bar(at(x1), at(y1), at(x2), at(y2), W);
const dot = (x: number, y: number) => disc(at(x), at(y), 0.35);

